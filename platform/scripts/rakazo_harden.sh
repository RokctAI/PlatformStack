#!/bin/bash
# =============================================================================
# RokctAI - Sticks server (Rakazo) hardening
# Idempotent. Edits the stack's .env only. Never prints secret values.
# Usage: RAKAZO_ENV_FILE=/opt/rakazo/.env [SIGNUP_ALLOWLIST=a@x.com,@corp.com] rakazo_harden.sh
# =============================================================================
set -Eeuo pipefail
umask 077

ENV_FILE="${RAKAZO_ENV_FILE:-.env}"
SIGNUP_ALLOWLIST_VALUE="${SIGNUP_ALLOWLIST:-}"

[ -f "${ENV_FILE}" ] || {
  echo "ERROR: env file not found: ${ENV_FILE}" >&2
  exit 1
}

# set_kv KEY VALUE: replace ALL active lines; else uncomment the first
# commented one; else append. Value is passed via the environment (no escaping).
set_kv() {
  KV_KEY="$1" KV_VAL="$2" python3 - "${ENV_FILE}" <<'PY'
import os, re, sys
p = sys.argv[1]; k = os.environ["KV_KEY"]; v = os.environ["KV_VAL"]
lines = open(p).read().split("\n")
act = [i for i, l in enumerate(lines) if re.match(rf"^\s*(?:export\s+)?{re.escape(k)}=", l)]
if act:
    for n, i in enumerate(act):
        lines[i] = f"{k}={v}" if n == 0 else None
    lines = [l for l in lines if l is not None]
else:
    com = [i for i, l in enumerate(lines) if re.match(rf"^#\s*{re.escape(k)}=", l)]
    if com:
        lines[com[0]] = f"{k}={v}"
    else:
        if lines and lines[-1] == "":
            lines.pop()
        lines.append(f"{k}={v}"); lines.append("")
open(p, "w").write("\n".join(lines))
PY
}

# has_value KEY: true when the last active assignment is non-empty (not "" or '').
has_value() {
  local v
  v=$(grep -E "^[[:space:]]*(export[[:space:]]+)?$1=" "${ENV_FILE}" | tail -n1 | cut -d= -f2-)
  v="${v%\"}"
  v="${v#\"}"
  v="${v%\'}"
  v="${v#\'}"
  [ -n "${v}" ]
}

# verify KEY VALUE: the file must now end with exactly this assignment.
FAILED=0
verify() {
  local got
  got=$(grep -E "^[[:space:]]*(export[[:space:]]+)?$1=" "${ENV_FILE}" | tail -n1 | cut -d= -f2-)
  if [ "${got}" != "$2" ]; then
    echo "ERROR: $1 is not '$2' after edit" >&2
    FAILED=1
  fi
}

# 1. Sign-ups: closed unless an allowlist is given.
if [ -n "${SIGNUP_ALLOWLIST_VALUE}" ]; then
  set_kv SIGNUPS_ENABLED true
  set_kv SIGNUP_ALLOWLIST "${SIGNUP_ALLOWLIST_VALUE}"
  verify SIGNUPS_ENABLED true
  verify SIGNUP_ALLOWLIST "${SIGNUP_ALLOWLIST_VALUE}"
  echo "signups: allowlist only"
else
  set_kv SIGNUPS_ENABLED false
  verify SIGNUPS_ENABLED false
  echo "signups: closed"
fi

# 2. Sandbox computers: public-internet egress only (no host/LAN/metadata).
set_kv SANDBOX_COMPUTER_EGRESS restricted
verify SANDBOX_COMPUTER_EGRESS restricted
echo "sandbox egress: restricted"

# 3. Never allow plain-http secrets to private hosts.
set_kv RAKAZO_SECRETS_ALLOW_PRIVATE_HTTP 0
verify RAKAZO_SECRETS_ALLOW_PRIVATE_HTTP 0
echo "private-http secrets: off"

# 4. Required secrets (shape only, values never printed). ENCRYPTION_KEY is
#    only generated on request: a new key makes stored secrets unreadable.
for k in BETTER_AUTH_SECRET SANDBOX_SUPERVISOR_TOKEN ENCRYPTION_KEY; do
  if has_value "${k}"; then
    echo "${k}: set"
  elif [ "${k}" = "ENCRYPTION_KEY" ] && [ "${RAKAZO_GENERATE_ENCRYPTION_KEY:-0}" != "1" ]; then
    echo "ERROR: ENCRYPTION_KEY is empty. Set it from the key store, or RAKAZO_GENERATE_ENCRYPTION_KEY=1 on a brand-new install only." >&2
    FAILED=1
  else
    set_kv "${k}" "$(openssl rand -hex 32)"
    echo "${k}: generated"
  fi
done
chmod 600 "${ENV_FILE}"

# 5. Shared host (Rakazo runs beside Frappe): replace the raw Docker socket
#    mount with a filtering socket proxy, on an internal-only network.
#    NOTE: this proxy limits Docker endpoints only. It does NOT stop a compromised
#    supervisor creating a privileged container or exec-ing into any container
#    (including Frappe). Needs Docker Compose >= 2.24 (uses !override).
#    Writes an override file; start with: docker compose -f <base> -f docker-compose.hardening.yml up -d
OVERRIDE="${RAKAZO_OVERRIDE_FILE:-$(dirname "${ENV_FILE}")/docker-compose.hardening.yml}"
cat >"${OVERRIDE}" <<'YML'
# Generated by rakazo_harden.sh. Safe to regenerate.
services:
  docker-proxy:
    image: tecnativa/docker-socket-proxy:0.3.0
    restart: unless-stopped
    environment:
      CONTAINERS: 1
      EXEC: 1
      POST: 1
      IMAGES: 1
      NETWORKS: 1
      INFO: 1
      VERSION: 1
      PING: 1
      VOLUMES: 0
      SERVICES: 0
      SWARM: 0
      SECRETS: 0
      CONFIGS: 0
      PLUGINS: 0
      BUILD: 0
      COMMIT: 0
      AUTH: 0
      SYSTEM: 0
      NODES: 0
      TASKS: 0
      DISTRIBUTION: 0
      EVENTS: 0
    volumes:
      - /var/run/docker.sock:/var/run/docker.sock:ro
    networks:
      - dockerproxy
    read_only: true
    tmpfs: [/run]
    cap_drop: [ALL]
    security_opt: ["no-new-privileges:true"]
  supervisor:
    environment:
      DOCKER_HOST: tcp://docker-proxy:2375
    volumes: !override
      - appdata:/data
    networks: !override
      - app
      - dockerproxy
    depends_on:
      - docker-proxy
networks:
  dockerproxy:
    internal: true
YML
chmod 600 "${OVERRIDE}"
echo "docker socket: proxy override written to ${OVERRIDE} (apply it with docker compose -f ... -f ${OVERRIDE})"

# 6. Approvals are a per-user setting (not env): remind, cannot force.
echo "RESIDUAL RISK: the proxy only removes volume/system/build/swarm endpoints. It does NOT stop a compromised supervisor from creating a privileged container or running commands in ANY container on this host, including Frappe. Keep the supervisor image current."
echo "NOTE: keep each user's Approvals mode on Ask or Auto, never 'Never ask'; avoid 'Always allow' on our own backend for bots that browse the web."
[ "${FAILED}" = "0" ] || {
  echo "FAILED: see errors above" >&2
  exit 1
}
echo "Restart the Rakazo stack for these changes to apply."
echo "done"
