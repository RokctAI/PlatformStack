"""Turn platform/sites/sites.json into the two files the Master VPS runs from.

- platform/docker-compose.sites.yml: one service per site, built with the generic
  shell image (juvo-shell/Dockerfile) at the site's pinned ref, on rokct_tenants as
  site-<name>:3000. docker-compose.yml includes it, so deploy-master's
  `docker compose up -d` starts every site.
- platform/sites/routes/routes.list: "<domain> <upstream>" per line. rokct-ingress writes a
  vhost per line (HTTP + ACME until a cert exists, then HTTPS) and hub-cert issues
  and renews the certs. No hand-written nginx, no pm2.

Rollback: set the site's ref back to the previous commit and redeploy; each ref is its
own image tag, so the old image is reused.

  python3 platform/scripts/sites.py          # write both files
  python3 platform/scripts/sites.py --check  # exit 1 if they are stale (CI)
"""
import json
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent.parent
SITES = HERE / "sites" / "sites.json"
COMPOSE = HERE / "docker-compose.sites.yml"
ROUTES = HERE / "sites" / "routes" / "routes.list"

NAME = re.compile(r"^[a-z0-9][a-z0-9-]{0,40}$")
DOMAIN = re.compile(r"^(?=.{1,253}$)([a-z0-9]([a-z0-9-]{0,61}[a-z0-9])?\.)+[a-z]{2,63}$")
REF = re.compile(r"^[A-Za-z0-9._/-]{1,100}$")
REPO = re.compile(r"^https://github\.com/[A-Za-z0-9._-]+/[A-Za-z0-9._-]+(\.git)?$")
MEM = re.compile(r"^[0-9]{2,5}[mM]$|^[0-9]{1,2}[gG]$")
APP = re.compile(r"^[A-Z][A-Z0-9]{0,30}$")


def load(path=SITES):
    data = json.loads(path.read_text())
    sites = data.get("sites", [])
    seen, domains = set(), set()
    for s in sites:
        n = s.get("name", "")
        if not NAME.match(n) or n in seen:
            raise SystemExit(f"bad or duplicate site name: {n!r}")
        seen.add(n)
        if not REPO.match(s.get("repo", "")):
            raise SystemExit(f"{n}: repo must be https://github.com/<owner>/<repo>")
        if not REF.match(s.get("ref", "main")):
            raise SystemExit(f"{n}: bad ref")
        if not MEM.match(s.get("memory", "512m")):
            raise SystemExit(f"{n}: memory like 512m or 1g")
        if "app" in s and not APP.match(s["app"]):
            raise SystemExit(f"{n}: app must be an env prefix like STICKS")
        ds = s.get("domains") or []
        if not ds:
            raise SystemExit(f"{n}: needs at least one domain")
        for d in ds:
            if not DOMAIN.match(d) or d in domains:
                raise SystemExit(f"{n}: bad or duplicate domain {d!r}")
            domains.add(d)
    return sites


def render_compose(sites):
    out = [
        "# GENERATED by platform/scripts/sites.py from platform/sites/sites.json. Do not edit.",
        "# One Next.js site per service, built by the generic shell image; rokct-ingress routes",
        "# each domain in sites/routes/routes.list to site-<name>:3000.",
    ]
    if not sites:
        out.append("services: {}")
        return "\n".join(out) + "\n"
    out.append("services:")
    for s in sites:
        n, ref = s["name"], s.get("ref", "main")
        url = "https://" + s["domains"][0]
        out += [
            f"  site-{n}:",
            "    build:",
            "      context: ./juvo-shell",
            "      args:",
            f"        SHELL_REPO: {json.dumps(s['repo'])}",
            f"        SHELL_REF: {json.dumps(ref)}",
            f"        NEXT_PUBLIC_SITE_URL: {json.dumps(url)}",
            "      secrets:",
            "        - git_token",
            "        # Build-time env (NEXT_PUBLIC_* are inlined by Next.js), written by deploy-master",
            "        # from Occultation's website block (platform/scripts/site_env.py).",
            f"        - source: site_env_{n}",
            "          target: site_env",
            f"    image: {json.dumps(f'rokct/site-{n}:' + ref.replace('/', '-'))}",
            "    pull_policy: build",
            "    # Started by deploy-master after the hub, one build at a time; a failed site never fails the hub.",
            "    profiles: [\"sites\"]",
            "    restart: unless-stopped",
            "    env_file:",
            f"      - path: ./sites/{n}.env",
            "        required: false",
            "    environment:",
            "      - NODE_ENV=production",
            "      - PORT=3000",
            "      - HOSTNAME=0.0.0.0",
            "    networks:",
            "      rokct_tenants:",
            "        aliases:",
            f"          - site-{n}",
            "    deploy:",
            "      resources:",
            "        limits:",
            f"          memory: {s.get('memory', '512m')}",
        ]
    out += [
        "secrets:",
        "  git_token:",
        "    # Optional: a token that can read private site repos, put on the VPS by deploy-master.",
        "    file: ./sites/.git_token",
    ]
    for s in sites:
        out += [f"  site_env_{s['name']}:", f"    file: ./sites/{s['name']}.env"]
    return "\n".join(out) + "\n"


def render_routes(sites):
    lines = ["# GENERATED by platform/scripts/sites.py. <domain> <upstream>"]
    for s in sites:
        for d in s["domains"]:
            lines.append(f"{d} http://site-{s['name']}:3000")
    return "\n".join(lines) + "\n"


def main(argv):
    sites = load()
    want = {COMPOSE: render_compose(sites), ROUTES: render_routes(sites)}
    if "--check" in argv:
        stale = [p.name for p, t in want.items() if not p.exists() or p.read_text() != t]
        if stale:
            print("stale, run python3 platform/scripts/sites.py: " + ", ".join(stale))
            return 1
        return 0
    for p, t in want.items():
        p.write_text(t)
    print(f"{len(sites)} site(s) written")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
